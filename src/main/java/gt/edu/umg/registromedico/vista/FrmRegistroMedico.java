    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (txtNombre.getText().trim().isEmpty() ||
        txtTelefono.getText().trim().isEmpty() ||
        txtDireccion.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Nombre, teléfono y dirección son obligatorios.");
        return;
    }

    String nombre = txtNombre.getText().trim();
    String telefono = txtTelefono.getText().trim();
    String direccion = txtDireccion.getText().trim();
    String tipoSangre = cmbTipoSangre.getSelectedItem().toString();
    String alergias = txtAlergias.getText().trim();

    String sql = "INSERT INTO Registro_Medico (nombre_completo, telefono, direccion, tipo_sangre, alergias) "
               + "VALUES (?, ?, ?, ?, ?)";

    try {
        Connection cn = Conexion.conectar();
        PreparedStatement ps = cn.prepareStatement(sql, PreparedStatement.RETURN_GENERATED_KEYS);
        ps.setString(1, nombre);
        ps.setString(2, telefono);
        ps.setString(3, direccion);
        ps.setString(4, tipoSangre);
        ps.setString(5, alergias);
        ps.executeUpdate();

        // 🔑 Recuperar el ID generado por SQL Server
        ResultSet rs = ps.getGeneratedKeys();
        if (rs.next()) {
            int idGenerado = rs.getInt(1);
            txtId.setText(String.valueOf(idGenerado));
        }

        JOptionPane.showMessageDialog(this, "Registro guardado correctamente. ID: " + txtId.getText());

        // ❌ NO llamamos a limpiar() para que el ID quede visible
        // Si prefieres limpiar, comenta la línea siguiente:
        // limpiar();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al guardar:\n" + e.getMessage());
    }
        
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarPorIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarPorIdActionPerformed
        String input = JOptionPane.showInputDialog(this, "Ingrese el ID a buscar:");
    if (input == null || input.trim().isEmpty()) {
        return;
    }

    int id;
    try {
        id = Integer.parseInt(input.trim());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El ID debe ser un número.");
        return;
    }

    String sql = "SELECT * FROM Registro_Medico WHERE id = ?";

    try {
        Connection cn = Conexion.conectar();
        PreparedStatement ps = cn.prepareStatement(sql);
        ps.setInt(1, id);
        ResultSet rs = ps.executeQuery();

        if (rs.next()) {
            txtId.setText(String.valueOf(rs.getInt("id")));
            txtNombre.setText(rs.getString("nombre_completo"));
            txtTelefono.setText(rs.getString("telefono"));
            txtDireccion.setText(rs.getString("direccion"));
            cmbTipoSangre.setSelectedItem(rs.getString("tipo_sangre"));
            txtAlergias.setText(rs.getString("alergias"));

            JOptionPane.showMessageDialog(this, "Registro encontrado.");
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró un registro con ese ID.");
            limpiar();
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al buscar:\n" + e.getMessage());
    }
    }//GEN-LAST:event_btnBuscarPorIdActionPerformed

    private void btnListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarActionPerformed
        String sql = "SELECT * FROM Registro_Medico ORDER BY id";

    try {
        Connection cn = Conexion.conectar();
        PreparedStatement ps = cn.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        StringBuilder sb = new StringBuilder();
        sb.append("ID\tNombre\tTeléfono\tDirección\tTipo Sangre\tAlergias\n");
        sb.append("-------------------------------------------------------------------------------------------------\n");

        while (rs.next()) {
            sb.append(rs.getInt("id")).append("\t")
              .append(rs.getString("nombre_completo")).append("\t")
              .append(rs.getString("telefono")).append("\t")
              .append(rs.getString("direccion")).append("\t")
              .append(rs.getString("tipo_sangre")).append("\t")
              .append(rs.getString("alergias")).append("\n");
        }

        txtAreaDatos.setText(sb.toString());
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al listar:\n" + e.getMessage());
    }
    }//GEN-LAST:event_btnListarActionPerformed

    private void btnpPorIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnpPorIdActionPerformed
         String input = JOptionPane.showInputDialog(this, "Ingrese el ID a mostrar:");
    if (input == null || input.trim().isEmpty()) {
        return;
    }

    int id;
    try {
        id = Integer.parseInt(input.trim());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El ID debe ser un número.");
        return;
    }

    String sql = "SELECT * FROM Registro_Medico WHERE id = ?";

    try {
        Connection cn = Conexion.conectar();
        PreparedStatement ps = cn.prepareStatement(sql);
        ps.setInt(1, id);
        ResultSet rs = ps.executeQuery();

        StringBuilder sb = new StringBuilder();
        sb.append("ID\tNombre\tTeléfono\tDirección\tTipo Sangre\tAlergias\n");
        sb.append("-------------------------------------------------------------------------------------------------\n");

        boolean encontrado = false;
        while (rs.next()) {
            encontrado = true;
            sb.append(rs.getInt("id")).append("\t")
              .append(rs.getString("nombre_completo")).append("\t")
              .append(rs.getString("telefono")).append("\t")
              .append(rs.getString("direccion")).append("\t")
              .append(rs.getString("tipo_sangre")).append("\t")
              .append(rs.getString("alergias")).append("\n");
        }

        if (encontrado) {
            txtAreaDatos.setText(sb.toString());
        } else {
            txtAreaDatos.setText("No se encontró un registro con ese ID.");
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al consultar:\n" + e.getMessage());
    }
    }//GEN-LAST:event_btnpPorIdActionPerformed

